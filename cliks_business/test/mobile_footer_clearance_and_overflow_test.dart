import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:clicks_business_frontend/core/navigation/navigation_provider.dart';
import 'package:clicks_business_frontend/features/navigation/widgets/top_nav_bar.dart';
import 'package:clicks_business_frontend/features/billing/pages/purchase_details_page.dart';
import 'package:clicks_business_frontend/features/billing/pages/staff_details_page.dart';
import 'package:clicks_business_frontend/features/payments/pages/cash_flow_heatmap_page.dart';
import 'package:clicks_business_frontend/features/dashboard/dashboard_page.dart';
import 'package:clicks_business_frontend/features/billing/pages/tax_deductions_page.dart';

void main() {
  group('Mobile UI, Overflows & Footer Clearance Tests', () {
    testWidgets('TopNavBar displays "cliks" when on Profile route (flutter_02.png)', (tester) async {
      tester.view.physicalSize = const Size(390, 844);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(() {
        tester.view.resetPhysicalSize();
        tester.view.resetDevicePixelRatio();
      });

      final container = ProviderContainer();
      container.read(navigationProvider.notifier).setModuleAndRoute(AppModule.profile, AppRoute.profile);

      await tester.pumpWidget(
        UncontrolledProviderScope(
          container: container,
          child: const MaterialApp(
            home: Scaffold(
              body: TopNavBar(),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();

      expect(find.text('cliks'), findsOneWidget);
      expect(tester.takeException(), isNull);
    });

    testWidgets('PurchaseDetailsPage Link External Store dialog does not overflow on Mobile (flutter_05.png)', (tester) async {
      tester.view.physicalSize = const Size(360, 780);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(() {
        tester.view.resetPhysicalSize();
        tester.view.resetDevicePixelRatio();
      });

      await tester.pumpWidget(
        const ProviderScope(
          child: MaterialApp(
            home: Scaffold(
              body: PurchaseDetailsPage(),
            ),
          ),
        ),
      );
      expect(find.text('Purchase Details'), findsOneWidget);

      // Open Link External Store Dialog
      await tester.ensureVisible(find.text('LINK EXTERNAL STORE'));
      await tester.tap(find.text('LINK EXTERNAL STORE'));
      await tester.pumpAndSettle();

      expect(find.text('Link External Store / POS'), findsOneWidget);
      expect(find.text('Connect your retail merchant counter or online storefront:'), findsOneWidget);

      expect(tester.takeException(), isNull);

      // Close dialog
      await tester.tap(find.text('Cancel'));
      await tester.pumpAndSettle();
    });

    testWidgets('StaffDetailsPage unlocked active integration and headers do not overflow on Mobile (flutter_06.png, flutter_07.png)', (tester) async {
      tester.view.physicalSize = const Size(360, 780);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(() {
        tester.view.resetPhysicalSize();
        tester.view.resetDevicePixelRatio();
      });

      await tester.pumpWidget(
        const ProviderScope(
          child: MaterialApp(
            home: Scaffold(
              body: StaffDetailsPage(),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();

      // Accept invitation to unlock
      await tester.ensureVisible(find.text('Accept'));
      await tester.pumpAndSettle();
      await tester.tap(find.text('Accept'));
      await tester.pumpAndSettle();

      // 1. Integration active & verified row (flutter_06.png)
      expect(find.text('Integration active & verified'), findsOneWidget);
      expect(find.text('Reset Status'), findsOneWidget);

      // 2. Residential Address Header (flutter_07.png)
      await tester.ensureVisible(find.text('RESIDENTIAL ADDRESS & EMERGENCY CONTACTS'));
      await tester.pumpAndSettle();
      expect(find.text('RESIDENTIAL ADDRESS & EMERGENCY CONTACTS'), findsOneWidget);
      expect(find.text('HR SUBMITTED RECORD'), findsOneWidget);

      // 3. Disbursed Payslips Header (flutter_07.png)
      await tester.ensureVisible(find.text('DISBURSED PAYSLIPS'));
      await tester.pumpAndSettle();
      expect(find.text('DISBURSED PAYSLIPS'), findsOneWidget);
      expect(find.text('Generated by santhoshhhhh(HR)'), findsOneWidget);

      // Verify ZERO RenderFlex overflow
      expect(tester.takeException(), isNull);
    });

    testWidgets('CashFlowHeatmapPage renders with clearance and without overflow on Mobile (flutter_01.png)', (tester) async {
      tester.view.physicalSize = const Size(360, 780);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(() {
        tester.view.resetPhysicalSize();
        tester.view.resetDevicePixelRatio();
      });

      await tester.pumpWidget(
        const ProviderScope(
          child: MaterialApp(
            home: Scaffold(
              body: CashFlowHeatmapPage(),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();

      expect(find.text('Cash Flow Heatmap & Peak Days'), findsOneWidget);
      expect(find.text('Spending Intensity Heatmap'), findsOneWidget);

      await tester.ensureVisible(find.text('Weekday Outflow Breakdown'));
      await tester.pumpAndSettle();
      expect(find.text('Weekday Outflow Breakdown'), findsOneWidget);
      expect(tester.takeException(), isNull);
    });

    testWidgets('DashboardPage and TaxDeductionsPage render with bottom clearance on Mobile (flutter_03.png, flutter_04.png)', (tester) async {
      tester.view.physicalSize = const Size(360, 780);
      tester.view.devicePixelRatio = 1.0;
      addTearDown(() {
        tester.view.resetPhysicalSize();
        tester.view.resetDevicePixelRatio();
      });

      // Dashboard
      await tester.pumpWidget(
        const ProviderScope(
          child: MaterialApp(
            home: Scaffold(
              body: DashboardPage(),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();
      expect(find.text('View Joint Expenses'), findsOneWidget);
      expect(tester.takeException(), isNull);

      // Tax Deductions
      await tester.pumpWidget(
        const ProviderScope(
          child: MaterialApp(
            home: Scaffold(
              body: TaxDeductionsPage(),
            ),
          ),
        ),
      );
      await tester.pumpAndSettle();
      expect(find.text('Tax Compliance'), findsOneWidget);
      expect(tester.takeException(), isNull);
    });
  });
}
